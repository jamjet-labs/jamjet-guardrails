"""Turn results/measurements.json into RESULTS.md. Standard library only.

`tests/test_unicode_scanner_benchmark.py` re-renders the committed file from
the committed JSON and fails on any difference, so RESULTS.md cannot be edited
by hand into saying something the measurement did not.

    python benchmarks/unicode-scanners/render.py
"""

from __future__ import annotations

import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
CORPUS = HERE / "corpus.jsonl"
TOOLS = HERE / "tools.json"
MEASUREMENTS = HERE / "results" / "measurements.json"
OUT = HERE / "RESULTS.md"

OURS = "jamjet-guardrails"


def _load() -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    corpus = [json.loads(x) for x in CORPUS.read_text(encoding="utf-8").splitlines() if x]
    tools = json.loads(TOOLS.read_text(encoding="utf-8"))["tools"]
    data = json.loads(MEASUREMENTS.read_text(encoding="utf-8"))
    return corpus, tools, data


def flagged(decision: str) -> bool:
    """An error counts as a flag: a CI step that errors fails the build."""
    return decision in ("flag", "error")


def score(corpus: Sequence[Mapping[str, Any]], decisions: Mapping[str, str]) -> dict[str, int]:
    s = {"tp": 0, "fp": 0, "fn": 0, "tn": 0, "errors": 0}
    for case in corpus:
        d = decisions[case["id"]]
        s["errors"] += d == "error"
        positive = case["expect"] == "flag"
        if flagged(d):
            s["tp" if positive else "fp"] += 1
        else:
            s["fn" if positive else "tn"] += 1
    return s


def _ratio(num: int, den: int) -> str:
    return "n/a" if den == 0 else f"{num / den:.3f}"


def _wrong(
    corpus: Sequence[Mapping[str, Any]], decisions: Mapping[str, str]
) -> list[Mapping[str, Any]]:
    return [c for c in corpus if flagged(decisions[c["id"]]) != (c["expect"] == "flag")]


def render(corpus: list[dict[str, Any]], tools: list[dict[str, Any]], data: dict[str, Any]) -> str:
    order = [t for t in tools if t["id"] in data["decisions"]]
    pos = sum(c["expect"] == "flag" for c in corpus)
    neg = len(corpus) - pos
    out: list[str] = []
    w = out.append
    w("# Hidden-Unicode scanners on one corpus\n")
    w("Generated by `benchmarks/unicode-scanners/render.py` from `results/measurements.json`.")
    w("Do not edit by hand: `tests/test_unicode_scanner_benchmark.py` re-renders this file and")
    w("fails on any difference.\n")
    w(
        f"Measured on **{data['measured']}** on {data['platform']}, Python {data['python']} "
        f"(Unicode {data['unicode']}), Node {data['node']}. Network access was "
        f"{'denied to every scanner by the operating system sandbox' if data['network_denied'] else 'NOT denied'} "
        "while it ran.\n"
    )
    w(
        f"The corpus is {len(corpus)} files: {pos} carry content a reviewer cannot see and "
        f"should be flagged, and {neg} are hard negatives, ordinary writing that uses "
        "invisible or format characters on purpose and should pass. Every case is in "
        "[`corpus.jsonl`](corpus.jsonl), built from code points by "
        "[`build_corpus.py`](build_corpus.py).\n"
    )
    w("## Read this before the numbers\n")
    w(
        "- **We wrote this corpus, and we also wrote one of the scanners.** The cases were "
        "written after `jamjet-guardrails`' detector existed, by people who knew what it "
        "catches. Read every number for it as self-graded. The third-party rows are scored "
        "on the same files by the same harness, and nothing here was tuned per tool.\n"
        "- **Labels are a judgement:** `flag` where a file carries text that renders as "
        "something other than what an agent reads, `pass` where every unusual character is "
        "ordinary writing. Some tools treat a stray joiner or a non-breaking space as worth "
        "a failed build on purpose; on this corpus that scores as a false positive.\n"
        "- **Defaults only, one decision per file, read from the exit code.** Several "
        "scanners report more than they fail on (ghostchars and hidden-content-scan both "
        "have warning levels that exit 0). Only what fails the step is scored here.\n"
        "- **The `encoded` family favours us.** Three of its four cases are JSON escapes in "
        "agent configuration, which `jamjet-guardrails scan` decodes and the others do not "
        "claim to. They were added at the same time as that decoding.\n"
        "- **The naive row is a rule, not Snyk's scanner.** It flags any Cf or Cc "
        "character, the rule Snyk Agent Scan's W021 issue code describes. Snyk's "
        "scanner itself was not run.\n"
    )
    w("## Scores\n")
    w(
        f"| Scanner | Version | Flagged hidden (of {pos}) | Flagged clean (of {neg}) "
        "| Errors | Precision | Recall | False-positive rate |"
    )
    w("|---|---|---:|---:|---:|---:|---:|---:|")
    for t in order:
        s = score(corpus, data["decisions"][t["id"]])
        w(
            f"| {t['name']} | `{data['versions'][t['id']]}` | {s['tp']} | {s['fp']} | {s['errors']} "
            f"| {_ratio(s['tp'], s['tp'] + s['fp'])} | {_ratio(s['tp'], pos)} | {_ratio(s['fp'], neg)} |"
        )
    w("")
    w("## Every wrong decision, ours first\n")
    w(
        "A miss is a `flag` case the scanner passed; a false positive is a `pass` case it "
        "flagged. Each case id is a line in `corpus.jsonl`.\n"
    )
    for t in order:
        wrong = _wrong(corpus, data["decisions"][t["id"]])
        misses = [c for c in wrong if c["expect"] == "flag"]
        fps = [c for c in wrong if c["expect"] == "pass"]
        w(f"### {t['name']}\n")
        w(f"{len(misses)} missed, {len(fps)} false positive{'s' if len(fps) != 1 else ''}.\n")
        for label, cases in (("Missed", misses), ("False positive", fps)):
            for c in cases:
                extra = f" Already known: {c['ours']}." if t["id"] == OURS and c["ours"] else ""
                w(f"- {label}: `{c['id']}`, {c['note']}.{extra}")
        if wrong:
            w("")
    w("## By family\n")
    w("Each cell is how many of the family's cases the scanner got right.\n")
    families: list[tuple[str, str]] = []
    for c in corpus:
        key = (c["family"], c["expect"])
        if key not in families:
            families.append(key)
    w("| Family | Should | Cases | " + " | ".join(t["name"] for t in order) + " |")
    w("|---|---|---:|" + "---:|" * len(order))
    for fam, expect in families:
        cases = [c for c in corpus if c["family"] == fam and c["expect"] == expect]
        cells = []
        for t in order:
            d = data["decisions"][t["id"]]
            cells.append(str(sum(flagged(d[c["id"]]) == (expect == "flag") for c in cases)))
        w(f"| {fam} | {expect} | {len(cases)} | " + " | ".join(cells) + " |")
    w("")
    w("## Every decision\n")
    w("Wrong decisions are in bold.\n")
    w("| Case | Should | " + " | ".join(t["id"] for t in order) + " |")
    w("|---|---|" + "---|" * len(order))
    for c in corpus:
        cells = []
        for t in order:
            d = data["decisions"][t["id"]][c["id"]]
            right = flagged(d) == (c["expect"] == "flag")
            cells.append(d if right else f"**{d}**")
        w(f"| `{c['id']}` | {c['expect']} | " + " | ".join(cells) + " |")
    w("")
    w("## What was run\n")
    w("| Scanner | Source | Pinned commit | Licence | Counts as a flag | Settings |")
    w("|---|---|---|---|---|---|")
    for t in order:
        commit = f"`{t['commit'][:12]}`" if "commit" in t else "this checkout"
        w(
            f"| [{t['name']}]({t['repo']}) | {t['registry']} | {commit} | {t['license']} | {t['flagged']} | {t['settings']} |"
        )
    w("")
    w(
        "The `jamjet-guardrails` and naive rows are measured from the checkout named in the "
        "Version column, and CI recomputes both from the code on every run. The other four "
        "rows are measured at the versions shown and are not recomputed by CI, because CI "
        "does not install them; [README.md](README.md) has the one command that reruns "
        "every row.\n"
    )
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render(*_load())
    if argv[1:] == ["--check"]:
        return 0 if OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
